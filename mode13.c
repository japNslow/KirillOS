void mode13_draw_char(int x, int y, char c, uint8_t color) {
    if ((uint8_t)c < 32 || (uint8_t)c > 127) c = 32;
    const uint8_t* glyph = FONT_8X8[(uint8_t)c - 32];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                mode13_put_pixel(x + col, y + row, color);
            }
        }
    }
}

void mode13_draw_string(int x, int y, const char* str, uint8_t color) {
    while (*str) {
        mode13_draw_char(x, y, *str++, color);
        x += 8;
    }
}

