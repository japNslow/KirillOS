void mode13_demo(void) {
    /* Play nice chime */
    sound_soft_note(523, 70);
    sound_soft_note(659, 70);
    sound_soft_note(784, 120);

    mode13_enter();

    /* 1. Background dark gradient */
    for (int y = 0; y < MODE13_HEIGHT; y++) {
        uint8_t bg_col = (uint8_t)(16 + (y * 16) / MODE13_HEIGHT);
        for (int x = 0; x < MODE13_WIDTH; x++) {
            mode13_put_pixel(x, y, bg_col);
        }
    }

    /* 2. Title Box */
    mode13_fill_rect(8, 6, 304, 28, 0); /* black backdrop */
    mode13_draw_rect(8, 6, 304, 28, 14); /* yellow border */
    mode13_draw_rect(9, 7, 302, 26, 11); /* cyan inner border */
    mode13_draw_string(24, 12, "KirillOS VGA Mode 13h (320x200 256c)", 15);
    mode13_draw_string(23, 11, "KirillOS VGA Mode 13h (320x200 256c)", 14);

    /* 3. Palette Spectrum Bar (256 colors) */
    mode13_draw_string(12, 38, "Full 256-Color Palette Spectrum:", 15);
    for (int i = 0; i < 256; i++) {
        int px = 32 + i;
        mode13_draw_line(px, 50, px, 62, (uint8_t)i);
    }
    mode13_draw_rect(31, 49, 258, 15, 15);

    /* 4. Geometric Primitives */
    /* Nested filled and outlined rectangles */
    mode13_fill_rect(20, 75, 70, 50, 4);   /* Red box */
    mode13_fill_rect(25, 80, 60, 40, 12);  /* Bright Red */
    mode13_fill_rect(30, 85, 50, 30, 14);  /* Yellow */
    mode13_draw_rect(20, 75, 70, 50, 15);

    /* Concentric Circles */
    for (int r = 5; r <= 30; r += 5) {
        mode13_draw_circle(160, 100, r, (uint8_t)(32 + r * 4));
    }
    mode13_fill_circle(160, 100, 6, 15);

    /* Raycasting starburst lines */
    int cx = 265, cy = 100;
    for (int a = 0; a < 16; a++) {
        int dx = (a < 8) ? (a * 6 - 24) : (24 - (a - 8) * 6);
        int dy = (a < 4 || a > 12) ? -24 : 24;
        mode13_draw_line(cx, cy, cx + dx, cy + dy, (uint8_t)(100 + a * 8));
    }

    /* 5. Subtitle Banner */
    mode13_fill_rect(10, 140, 300, 45, 1); /* Dark blue container */
    mode13_draw_rect(10, 140, 300, 45, 9);
    mode13_draw_string(20, 146, "DOOM, Wolfenstein 3D & Demoscene Era!", 10);
    mode13_draw_string(20, 158, "Hardware Framebuffer @ 0x000A0000", 11);
    mode13_draw_string(20, 170, ">> Press ANY KEY to exit Mode 13h <<", 15);

    /* 6. Dynamic Palette Cycling Animation Loop */
    uint8_t rot = 0;
    while (!keyboard_has_char()) {
        /* Rotate palette colors 32..255 for hypnotic smooth animation */
        rot++;
        for (int i = 0; i < 224; i += 4) {
            uint8_t idx = (uint8_t)(32 + i);
            int phase = (((i + rot * 2) & 0xFF) * 6) / 256;
            int step = (((i + rot * 2) & 0xFF) * 6) % 256;
            uint8_t val = (uint8_t)((step * 63) / 256);

            uint8_t r = 0, g = 0, b = 0;
            switch (phase) {
                case 0: r = 63; g = val; b = 0; break;
                case 1: r = (uint8_t)(63 - val); g = 63; b = 0; break;
                case 2: r = 0; g = 63; b = val; break;
                case 3: r = 0; g = (uint8_t)(63 - val); b = 63; break;
                case 4: r = val; g = 0; b = 63; break;
                default: r = 63; g = 0; b = (uint8_t)(63 - val); break;
            }
            mode13_set_palette(idx, r, g, b);
        }

        /* Short delay to keep animation smooth ~60 FPS */
        for (volatile int d = 0; d < 40000; d++);
    }

    /* Consume the key press */
    (void)keyboard_getchar();

    /* Clean exit back to text mode */
    mode13_exit();
}
