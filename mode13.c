/*                       2D Drawing Primitives                      */
/* ================================================================ */

void mode13_clear(uint8_t color) {
    uint8_t* vram = MODE13_VRAM;
    for (int i = 0; i < MODE13_WIDTH * MODE13_HEIGHT; i++) {
        vram[i] = color;
    }
}

void mode13_put_pixel(int x, int y, uint8_t color) {
    if (x >= 0 && x < MODE13_WIDTH && y >= 0 && y < MODE13_HEIGHT) {
        MODE13_VRAM[y * MODE13_WIDTH + x] = color;
    }
}

uint8_t mode13_get_pixel(int x, int y) {
    if (x >= 0 && x < MODE13_WIDTH && y >= 0 && y < MODE13_HEIGHT) {
        return MODE13_VRAM[y * MODE13_WIDTH + x];
    }
    return 0;
}

void mode13_draw_line(int x0, int y0, int x1, int y1, uint8_t color) {
    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int sx = (x0 < x1) ? 1 : -1;
    int dy = (y1 > y0) ? (y0 - y1) : (y1 - y0);
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx + dy;

    for (;;) {
        mode13_put_pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void mode13_draw_rect(int x, int y, int w, int h, uint8_t color) {
    if (w <= 0 || h <= 0) return;
    mode13_draw_line(x, y, x + w - 1, y, color);
    mode13_draw_line(x, y + h - 1, x + w - 1, y + h - 1, color);
    mode13_draw_line(x, y, x, y + h - 1, color);
    mode13_draw_line(x + w - 1, y, x + w - 1, y + h - 1, color);
}

void mode13_fill_rect(int x, int y, int w, int h, uint8_t color) {
    if (w <= 0 || h <= 0) return;
    int x2 = x + w;
    int y2 = y + h;
    if (x < 0) x = 0;
    if (y < 0) y = 0;
    if (x2 > MODE13_WIDTH) x2 = MODE13_WIDTH;
    if (y2 > MODE13_HEIGHT) y2 = MODE13_HEIGHT;

    uint8_t* vram = MODE13_VRAM;
    for (int cy = y; cy < y2; cy++) {
        int row_off = cy * MODE13_WIDTH;
        for (int cx = x; cx < x2; cx++) {
            vram[row_off + cx] = color;
        }
    }
}

void mode13_draw_circle(int xc, int yc, int r, uint8_t color) {
    int x = 0, y = r;
    int d = 3 - 2 * r;
    while (y >= x) {
        mode13_put_pixel(xc + x, yc + y, color);
        mode13_put_pixel(xc - x, yc + y, color);
        mode13_put_pixel(xc + x, yc - y, color);
        mode13_put_pixel(xc - x, yc - y, color);
        mode13_put_pixel(xc + y, yc + x, color);
        mode13_put_pixel(xc - y, yc + x, color);
        mode13_put_pixel(xc + y, yc - x, color);
        mode13_put_pixel(xc - y, yc - x, color);
        x++;
        if (d > 0) { y--; d = d + 4 * (x - y) + 10; }
        else d = d + 4 * x + 6;
    }
}

void mode13_fill_circle(int xc, int yc, int r, uint8_t color) {
    int x = 0, y = r;
    int d = 3 - 2 * r;
    while (y >= x) {
        mode13_draw_line(xc - x, yc + y, xc + x, yc + y, color);
        mode13_draw_line(xc - x, yc - y, xc + x, yc - y, color);
        mode13_draw_line(xc - y, yc + x, xc + y, yc + x, color);
        mode13_draw_line(xc - y, yc - x, xc + y, yc - x, color);
        x++;
        if (d > 0) { y--; d = d + 4 * (x - y) + 10; }
        else d = d + 4 * x + 6;
    }
}

