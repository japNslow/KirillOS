/* Plane 2 Font Backup (4096 bytes for 256 characters of 16 bytes each) */
static uint8_t font_backup[4096];
static int     font_saved = 0;

static void save_font(void) {
    outb(0x3C4, 0x00); outb(0x3C5, 0x01);
    outb(0x3C4, 0x02); outb(0x3C5, 0x04);
    outb(0x3C4, 0x04); outb(0x3C5, 0x06);
    outb(0x3C4, 0x00); outb(0x3C5, 0x03);

    outb(0x3CE, 0x04); outb(0x3CF, 0x02);
    outb(0x3CE, 0x05); outb(0x3CF, 0x00);
    outb(0x3CE, 0x06); outb(0x3CF, 0x04);

    volatile uint8_t* src = (volatile uint8_t*)0xA0000;
    for (int i = 0; i < 4096; i++) {
        font_backup[i] = src[i];
    }
    font_saved = 1;
}

static void restore_font(void) {
    if (!font_saved) return;
    outb(0x3C4, 0x00); outb(0x3C5, 0x01);
    outb(0x3C4, 0x02); outb(0x3C5, 0x04);
    outb(0x3C4, 0x04); outb(0x3C5, 0x06);
    outb(0x3C4, 0x00); outb(0x3C5, 0x03);

    outb(0x3CE, 0x04); outb(0x3CF, 0x02);
    outb(0x3CE, 0x05); outb(0x3CF, 0x00);
    outb(0x3CE, 0x06); outb(0x3CF, 0x04);

    volatile uint8_t* dst = (volatile uint8_t*)0xA0000;
    for (int i = 0; i < 4096; i++) {
        dst[i] = font_backup[i];
    }
}

/* ================================================================ */
/*                       Palette Programming                        */
/* ================================================================ */

void mode13_set_palette(uint8_t index, uint8_t r, uint8_t g, uint8_t b) {
    outb(0x3C8, index);
    outb(0x3C9, r & 0x3F);
    outb(0x3C9, g & 0x3F);
    outb(0x3C9, b & 0x3F);
}

static void init_default_palette(void) {
    /* Standard 16 VGA colors */
    static const uint8_t std16[16][3] = {
        {0, 0, 0},    {0, 0, 42},   {0, 42, 0},   {0, 42, 42},
        {42, 0, 0},   {42, 0, 42},  {42, 21, 0},  {42, 42, 42},
        {21, 21, 21}, {21, 21, 63}, {21, 63, 21}, {21, 63, 63},
        {63, 21, 21}, {63, 21, 63}, {63, 63, 21}, {63, 63, 63}
    };
    for (uint8_t i = 0; i < 16; i++) {
        mode13_set_palette(i, std16[i][0], std16[i][1], std16[i][2]);
    }

    /* 16..31: Grayscale gradient */
    for (uint8_t i = 0; i < 16; i++) {
        uint8_t gray = (uint8_t)(i * 4 + 3);
        mode13_set_palette(16 + i, gray, gray, gray);
    }

    /* 32..255: Smooth rainbow spectrum (7 bands of 32 colors) */
    for (int i = 0; i < 224; i++) {
        uint8_t idx = (uint8_t)(32 + i);
        int phase = (i * 6) / 224;
        int step = (i * 6) % 224;
        uint8_t val = (uint8_t)((step * 63) / 224);

        uint8_t r = 0, g = 0, b = 0;
        switch (phase) {
            case 0: r = 63; g = val; b = 0; break;
            case 1: r = 63 - val; g = 63; b = 0; break;
            case 2: r = 0; g = 63; b = val; break;
            case 3: r = 0; g = 63 - val; b = 63; break;
            case 4: r = val; g = 0; b = 63; break;
            default: r = 63; g = 0; b = 63 - val; break;
        }
        mode13_set_palette(idx, r, g, b);
    }
}

/* ================================================================ */
/*                       Mode 13h Enter & Exit                      */
/* ================================================================ */

void mode13_enter(void) {
    save_font();

    outb(0x3C4, 0x00); outb(0x3C5, 0x01);
    outb(0x3C2, mode13_misc);

    for (uint8_t i = 1; i < 5; i++) {
        outb(0x3C4, i);
        outb(0x3C5, mode13_seq[i]);
    }
    outb(0x3C4, 0x00); outb(0x3C5, 0x03);

    outb(0x3D4, 0x11);
    outb(0x3D5, (uint8_t)(inb(0x3D5) & 0x7F));

    for (uint8_t i = 0; i < 25; i++) {
        outb(0x3D4, i);
        outb(0x3D5, mode13_crtc[i]);
    }

    for (uint8_t i = 0; i < 9; i++) {
        outb(0x3CE, i);
        outb(0x3CF, mode13_gc[i]);
    }

    for (uint8_t i = 0; i < 21; i++) {
        (void)inb(0x3DA);
        outb(0x3C0, i);
        outb(0x3C0, mode13_ac[i]);
    }
    (void)inb(0x3DA);
    outb(0x3C0, 0x20);

    init_default_palette();
    mode13_clear(0);
}

void mode13_exit(void) {
    outb(0x3C4, 0x00); outb(0x3C5, 0x01);
    outb(0x3C2, mode03_misc);

    for (uint8_t i = 1; i < 5; i++) {
        outb(0x3C4, i);
        outb(0x3C5, mode03_seq[i]);
    }
    outb(0x3C4, 0x00); outb(0x3C5, 0x03);

    outb(0x3D4, 0x11);
    outb(0x3D5, (uint8_t)(inb(0x3D5) & 0x7F));

    for (uint8_t i = 0; i < 25; i++) {
        outb(0x3D4, i);
        outb(0x3D5, mode03_crtc[i]);
    }

    for (uint8_t i = 0; i < 9; i++) {
        outb(0x3CE, i);
        outb(0x3CF, mode03_gc[i]);
    }

    restore_font();

    for (uint8_t i = 1; i < 5; i++) {
        outb(0x3C4, i);
        outb(0x3C5, mode03_seq[i]);
    }
    for (uint8_t i = 0; i < 9; i++) {
        outb(0x3CE, i);
        outb(0x3CF, mode03_gc[i]);
    }

    for (uint8_t i = 0; i < 21; i++) {
        (void)inb(0x3DA);
        outb(0x3C0, i);
        outb(0x3C0, mode03_ac[i]);
    }
    (void)inb(0x3DA);
    outb(0x3C0, 0x20);

    vga_init();
    vga_clear();
}

